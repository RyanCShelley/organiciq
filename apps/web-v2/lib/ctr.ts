export type CtrPage = {
  url: string;
  title: string | null;
  impressions: number;
  clicks: number;
  ctr: number;
  expected_clicks: number;
  extra_clicks: number;
  position: number;
  searches: number;
  searches_below: number;
  top_search: string;
  below: boolean;
};
export type CtrSearch = { query: string; url: string; impressions: number; clicks: number; position: number; ctr: number; expected_ctr: number; expected_clicks: number; extra_clicks: number; below: boolean };
export type Ctr = {
  from: string;
  to: string;
  benchmark: string;
  rule: string;
  score: number | null;
  clicks: number;
  expected_clicks: number;
  extra_clicks: number;
  pages_below: number;
  searches_below: number;
  pages_counted: number;
  searches_counted: number;
  monthly: { month: string; score: number | null; extra_clicks: number; clicks: number; expected_clicks: number }[];
  pages: CtrPage[];
  searches: CtrSearch[];
  bing: { score: number; clicks: number; expected_clicks: number; searches: number } | null;
};
export type CtrWindow = { impressions: number; clicks: number; ctr: number; position: number } | null;
export type CtrDetail = {
  url: string;
  title: string | null;
  description: string | null;
  title_length: number | null;
  description_length: number | null;
  searches: (CtrSearch & { bing: { impressions: number; clicks: number; position: number | null } | null })[];
  searches_total: number;
  changes: { date: string; kind: string; text: string; before: CtrWindow; after: CtrWindow; measured_on: string | null }[];
  title_draft: CtrTitleDraft | null;
  model_ready: boolean;
};

export type CtrDepth = "quick" | "deep" | "deepest";
export type CtrTitleDraft = {
  id: string;
  status: "running" | "done" | "failed";
  error: string | null;
  depth: CtrDepth;
  cost_usd: number;
  created_by: string;
  created_at: string | null;
  from: string;
  to: string;
  title_now?: string | null;
  title_now_length?: number | null;
  diagnosis?: string;
  options?: { title: string; length: number; too_long: boolean; why: string; serves: string[] }[];
  recommended?: number;
  searches_used?: number;
  page_read?: boolean;
  pattern?: string | null;
};
